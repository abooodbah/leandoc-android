#!/bin/sh
# Copies the reader page, the document core and their pinned packages from a
# checkout of the desktop app, then rewrites third_party/reader-assets.sha256.
#
#   scripts/update-reader-assets.sh /path/to/leandoc
#
# The desktop checkout needs `npm ci` first, for docx-preview, JSZip and the
# fonts.
set -eu

desktop=${1:?usage: scripts/update-reader-assets.sh /path/to/leandoc}
here=$(cd "$(dirname "$0")/.." && pwd)
assets="$here/app/src/main/assets/reader"
cpp="$here/app/src/main/cpp"
modules="$desktop/node_modules"

mkdir -p "$assets/vendor" "$assets/fonts" "$cpp/core" "$cpp/miniz" "$cpp/pugixml"
for file in reader.css reader.js fixups.js fidelity.js; do
  cp "$desktop/assets/$file" "$assets/"
done
# The only change to the desktop script: fit width and automatic zoom may go
# below 50%, so a Letter or A4 page fits a phone's width. The steps of the
# zoom buttons stay as on the desktop. The check stops the update if the
# desktop line changes, so the patch is looked at again.
fit='return Math.max(0.5, Math.min(3, available / pageWidthPixels()));'
grep -qF "$fit" "$assets/reader.js"
sed -i 's|return Math.max(0.5, Math.min(3, available / pageWidthPixels()));|return Math.max(0.25, Math.min(3, available / pageWidthPixels()));|' \
  "$assets/reader.js"
grep -qF 'return Math.max(0.25, Math.min(3, available / pageWidthPixels()));' "$assets/reader.js"
# The only change to the desktop page: load the Android bridge first.
sed 's|^    <link rel="stylesheet" href="/reader.css" />$|&\n    <script src="/android-host.js"></script>|' \
  "$desktop/assets/reader.html" > "$assets/reader.html"
grep -q 'src="/android-host.js"' "$assets/reader.html"
cp "$modules/jszip/dist/jszip.min.js" "$modules/docx-preview/dist/docx-preview.min.js" "$assets/vendor/"
for font in \
  ibm-plex-sans/files/ibm-plex-sans-latin-400-normal \
  ibm-plex-sans/files/ibm-plex-sans-latin-500-normal \
  ibm-plex-sans/files/ibm-plex-sans-latin-600-normal \
  ibm-plex-serif/files/ibm-plex-serif-latin-600-normal \
  ibm-plex-mono/files/ibm-plex-mono-latin-400-normal \
  ibm-plex-sans-arabic/files/ibm-plex-sans-arabic-arabic-400-normal \
  ibm-plex-sans-arabic/files/ibm-plex-sans-arabic-arabic-600-normal; do
  cp "$modules/@fontsource/$font.woff2" "$assets/fonts/"
done
for file in Cfb DocCore Links Word Xml Zip; do
  cp "$desktop/src/core/$file.cpp" "$desktop/src/core/$file.h" "$cpp/core/"
done
cp "$desktop/src/core/Failure.h" "$cpp/core/"
cp "$desktop/third_party/miniz/miniz.c" "$desktop/third_party/miniz/miniz.h" \
  "$desktop/third_party/miniz/LICENSE" "$cpp/miniz/"
cp "$desktop/third_party/pugixml/pugixml.cpp" "$desktop/third_party/pugixml/pugixml.hpp" \
  "$desktop/third_party/pugixml/pugiconfig.hpp" "$desktop/third_party/pugixml/LICENSE.md" "$cpp/pugixml/"
cp "$desktop/tests/core/CoreTests.cpp" "$desktop/tests/core/TestZip.cpp" \
  "$desktop/tests/core/TestZip.h" "$here/native-tests/"
fixtures="$here/app/src/androidTest/assets/fixtures"
rm -rf "$fixtures"
mkdir -p "$fixtures"
cp -R "$desktop/tests/fixtures/features" "$desktop/tests/fixtures/kinds" \
  "$desktop/tests/fixtures/security" "$fixtures/"
cp "$desktop/tests/fixtures/expected.json" "$desktop/tests/fixtures/expected.inc" \
  "$desktop/tests/fixtures/README.md" "$desktop/tests/fixtures/make-fixtures.py" "$fixtures/"

cd "$here"
{
  echo "# Generated by scripts/update-reader-assets.sh from desktop commit $(git -C "$desktop" rev-parse HEAD)"
  find app/src/main/assets/reader app/src/main/cpp/core app/src/main/cpp/miniz \
    app/src/main/cpp/pugixml native-tests/CoreTests.cpp native-tests/TestZip.cpp \
    native-tests/TestZip.h app/src/androidTest/assets/fixtures \
    -type f ! -name android-host.js | LC_ALL=C sort | xargs sha256sum
} > third_party/reader-assets.sha256
echo "Updated. Review the diff, then run the tests."
